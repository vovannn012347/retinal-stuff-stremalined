"""Build the ProcessorApplication script package (definitor + classifier) and, optionally, the upload zip.

    python code_new/tools/build_processor_script.py
        refreshes code_new/processor_script/retinal_surgical_analyzer/code/rt_*.py from code_new/surgical/
        (the runtime modules are flat copies: the executor imports every script_file as a top-level module)

    python code_new/tools/build_processor_script.py ^
        --definitor training-runs/definitor_cpu_from_x16/final_model.pth ^
        --classifier training-runs/classifier_laptop/final_model.pth ^
        --zip dist/retinal_surgical_analyzer.zip
        also copies the weights into weights/ and writes the zip with script_manifest.json at the archive
        root (the provisioning page expects that). __pycache__, .pyc and hidden files are left out.
"""
import argparse
import json
import re
import shutil
import sys
import zipfile
from pathlib import Path

CODE = Path(__file__).resolve().parents[1]
SRC = CODE / 'surgical'
PKG = CODE / 'processor_script' / 'retinal_surgical_analyzer'

MODULES = {                       # source -> runtime module name
    'enhance.py': 'rt_enhance',
    'disc_crop.py': 'rt_disc_crop',
    'definitor_model.py': 'rt_definitor_model',
    'model.py': 'rt_model',
    'pipeline.py': 'rt_pipeline',
}
IMPORTS = [                       # package-relative imports -> flat imports
    (r'from \. import disc_crop as C', 'import rt_disc_crop as C'),
    (r'from \. import enhance as E', 'import rt_enhance as E'),
    (r'from \.definitor_model import', 'from rt_definitor_model import'),
    (r'from \.model import', 'from rt_model import'),
    (r'from \.vgg_init import', 'from vgg_init import'),       # training only, never called at inference
]
HEADER = '# GENERATED by code_new/tools/build_processor_script.py from code_new/surgical/{src} - edit the source, not this file\n'


def refresh_modules():
    out = PKG / 'code'
    out.mkdir(parents=True, exist_ok=True)
    for src, mod in MODULES.items():
        text = (SRC / src).read_text(encoding='utf-8')
        for pat, rep in IMPORTS:
            text = re.sub(pat, rep, text)
        left = re.findall(r'^\s*from \.\S* import .*$', text, flags=re.M)
        if left:
            sys.exit(f"{src}: relative import not translated: {left}")
        (out / f'{mod}.py').write_text(HEADER.format(src=src) + text, encoding='utf-8')
    print(f"runtime modules refreshed in {out}")


def excluded(rel: str) -> bool:
    parts = rel.split('/')
    return any(p.startswith('.') or p == '__pycache__' for p in parts) or rel.endswith(('.pyc', '.pyo'))


def check_package():
    m = json.loads((PKG / 'script_manifest.json').read_text(encoding='utf-8'))
    missing = [i['disk_path'] for i in m['inputs_mapping'] if i.get('disk_path') and not (PKG / i['disk_path']).is_file()]
    if not (PKG / m['entry_point']).is_file():
        missing.append(m['entry_point'])
    return m, missing


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--definitor', help='definitor model file -> weights/definitor.pth')
    ap.add_argument('--classifier', help='classifier model file -> weights/classifier.pth')
    ap.add_argument('--zip', help='write the upload zip here')
    a = ap.parse_args()

    refresh_modules()
    for src, name in ((a.definitor, 'definitor.pth'), (a.classifier, 'classifier.pth')):
        if src:
            shutil.copyfile(src, PKG / 'weights' / name)
            print(f"weights/{name} <- {src}")
    m, missing = check_package()
    if missing:
        print("missing files (put them in place before uploading): " + ', '.join(missing))
    if a.zip:
        if missing:
            sys.exit("not writing the zip while files are missing")
        out = Path(a.zip)
        out.parent.mkdir(parents=True, exist_ok=True)
        files = sorted(p for p in PKG.rglob('*') if p.is_file()
                       and not excluded(p.relative_to(PKG).as_posix()) and p.name != 'PUT_WEIGHTS_HERE.txt')
        with zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED) as z:
            for p in files:
                z.write(p, p.relative_to(PKG).as_posix())
        print(f"{out}: {len(files)} files, {out.stat().st_size / 1048576:.1f} MB "
              f"({m['script_label']} {m['version']})")


if __name__ == '__main__':
    main()
